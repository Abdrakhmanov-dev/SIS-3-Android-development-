 // Saved recipes are needed by several screens, so they live here as one source of truth.
 private val _favoriteIds = MutableStateFlow(storage.load())
 val favoriteIds: StateFlow<Set<Int>> = _favoriteIds.asStateFlow()

 suspend fun getRecipes(): List<Recipe> {
  delay(delayMillis)
  if (shouldFail) throw IOException("Simulated server error")
  return recipes
 }

 suspend fun getRecipe(id: Int): Recipe? {
  delay(delayMillis / 2)
  if (shouldFail) throw IOException("Simulated server error")
  return recipes.find { it.id == id }
 }

 fun toggleFavorite(id: Int) {
  val updated = _favoriteIds.updateAndGet { ids -> if (id in ids) ids - id else ids + id }
  storage.save(updated)
 }
}
